// Answering the sandbox: imports and host-function calls
// ---------------------------------------------------------------------------

/// How to answer an `import` from the sandbox.
pub enum ImportAnswer {
    /// A host module value (`_host`).
    Module(MontyObject),
    /// A `.py` file the sandbox runs as the module (the embedded SDK).
    File(ModuleFile),
    /// Not ours: let the sandbox raise `ModuleNotFoundError`.
    NotFound,
}

/// `import _host` gets the host module; `import dut[.x]` gets the embedded SDK file.
pub fn answer_import(args: &ImportArgs) -> ImportAnswer {
    if args.module == HOST_MODULE {
        let attrs = HOST_FUNCTIONS
            .iter()
            .map(|f| (MontyObject::string(*f), MontyObject::function(*f, None)));
        return ImportAnswer::Module(MontyObject::module(HOST_MODULE, HOST_MODULE_ID, attrs));
    }
    let prefix = format!("{SDK_DIR}/{SDK_MODULE}/");
    for path in args.candidates() {
        let Some(file) = path.strip_prefix(&prefix) else {
            continue;
        };
        if let Some((_, source)) = SDK_FILES.iter().find(|(name, _)| *name == file) {
            return ImportAnswer::File(ModuleFile {
                path,
                source: (*source).to_string(),
            });
        }
    }
    ImportAnswer::NotFound
}

/// A host-function call from the sandbox that needs the [`Host`](crate::Host).
#[derive(Debug, Clone, PartialEq)]
pub enum HostCall {
    Write { channel: String, data: Vec<u8> },
    NextEvent { timeout: Seconds },
    Now,
    Emit { kind: SignalKind, payload: Value },
}

/// A decoded host-function call: either it needs the host, or it was a pure data
/// helper and its result is already computed.
pub enum Decoded {
    Host(HostCall),
    Done(MontyObject),
}

/// Decode a call to a `_host` function. Errors are exceptions to raise in the sandbox.
pub fn decode_call(name: &str, args: &CallArgs) -> Result<Decoded, MontyException> {
    let a = Args { args, func: name };
    let value_err = |e: helpers::DataError| MontyException::new(ExcType::ValueError, Some(e.0));
    let done = |v: Value| Ok(Decoded::Done(to_monty(&v)));
    match name {
        "write" => Ok(Decoded::Host(HostCall::Write {
            data: a.bytes(0, "data")?,
            channel: a.opt_str(1, "channel")?.unwrap_or_else(|| "main".into()),
        })),
        "next_event" => Ok(Decoded::Host(HostCall::NextEvent {
            timeout: a.float(0, "timeout")?,
        })),
        "now" => Ok(Decoded::Host(HostCall::Now)),
        "emit" => Ok(Decoded::Host(HostCall::Emit {
            kind: SignalKind::from(a.str(0, "kind")?.as_str()),
            payload: a.get(1, "payload")?,
        })),
        "pack" => done(Value::Bytes(
            helpers::pack(&a.str(0, "fmt")?, &a.list(1, "values")?).map_err(value_err)?,
        )),
        "unpack" => done(Value::List(
            helpers::unpack(&a.str(0, "fmt")?, &a.bytes(1, "data")?).map_err(value_err)?,
        )),
        "crc" => done(Value::Int(
            helpers::crc(&a.str(0, "kind")?, &a.bytes(1, "data")?).map_err(value_err)? as i64,
        )),
        "cobs_encode" => done(Value::Bytes(helpers::cobs_encode(&a.bytes(0, "data")?))),
        "cobs_decode" => done(Value::Bytes(
            helpers::cobs_decode(&a.bytes(0, "data")?).map_err(value_err)?,
        )),
        "slip_encode" => done(Value::Bytes(helpers::slip_encode(&a.bytes(0, "data")?))),
        "slip_decode" => done(Value::Bytes(
            helpers::slip_decode(&a.bytes(0, "data")?).map_err(value_err)?,
        )),
        "bytes_from_list" => done(Value::Bytes(
            helpers::bytes_from_list(&a.list(0, "values")?).map_err(value_err)?,
        )),
        _ => Err(MontyException::new(
            ExcType::NameError,
            Some(format!("unknown host function {name:?}")),
        )),
    }
}

/// How a host failure is raised inside the sandbox.
pub fn host_exception(e: &HostError) -> MontyException {
    MontyException::new(ExcType::RuntimeError, Some(format!("host: {e}")))
}

/// What `next_event` returns to the sandbox: `{"kind", "channel", "data", "t"}`
/// (+ `"timer"` for ticks), or `None` at the timeout.
pub fn event_object(ev: Option<Event>) -> MontyObject {
    let Some(ev) = ev else {
        return MontyObject::none();
    };
    let (kind, data, timer) = match ev.kind {
        EventKind::Frame(d) => ("frame", Value::Bytes(d), None),
        EventKind::Packet(d) => ("packet", Value::Bytes(d), None),
        EventKind::Tick { timer } => ("tick", Value::None, Some(timer)),
    };
    let mut fields = vec![
        ("kind", Value::from(kind)),
        ("channel", ev.channel.map_or(Value::None, Value::Str)),
        ("data", data),
        ("t", Value::Float(ev.t)),
    ];
    if let Some(timer) = timer {
        fields.push(("timer", Value::Int(timer as i64)));
    }
    to_monty(&Value::dict(fields))
}

/// Positional-or-keyword access to a host call's arguments.
struct Args<'a> {
    args: &'a CallArgs,
    func: &'a str,
}

impl Args<'_> {
    fn opt(&self, i: usize, name: &str) -> Option<Value> {
        self.args
            .arg(i)
            .or_else(|| self.args.kwarg(name))
            .map(to_value)
    }

    fn get(&self, i: usize, name: &str) -> Result<Value, MontyException> {
        self.opt(i, name).ok_or_else(|| {
            MontyException::new(
                ExcType::TypeError,
                Some(format!("{}() missing argument {name:?}", self.func)),
            )
        })
    }

    fn type_err(&self, name: &str, expected: &str) -> MontyException {
        MontyException::new(
            ExcType::TypeError,
            Some(format!("{}(): {name} must be {expected}", self.func)),
        )
    }

    fn bytes(&self, i: usize, name: &str) -> Result<Vec<u8>, MontyException> {
        match self.get(i, name)? {
            Value::Bytes(b) => Ok(b),
            _ => Err(self.type_err(name, "bytes")),
        }
    }

    fn str(&self, i: usize, name: &str) -> Result<String, MontyException> {
        match self.get(i, name)? {
            Value::Str(s) => Ok(s),
            _ => Err(self.type_err(name, "str")),
        }
    }

    fn opt_str(&self, i: usize, name: &str) -> Result<Option<String>, MontyException> {
        match self.opt(i, name) {
            None | Some(Value::None) => Ok(None),
            Some(Value::Str(s)) => Ok(Some(s)),
            Some(_) => Err(self.type_err(name, "str")),
        }
    }

    fn float(&self, i: usize, name: &str) -> Result<f64, MontyException> {
        self.get(i, name)?
            .as_float()
            .ok_or_else(|| self.type_err(name, "a number"))
    }

    fn list(&self, i: usize, name: &str) -> Result<Vec<Value>, MontyException> {
        match self.get(i, name)? {
            Value::List(l) => Ok(l),
            _ => Err(self.type_err(name, "a list")),
        }
    }
}

// ---------------------------------------------------------------------------
// Value conversion
// ---------------------------------------------------------------------------

/// A sandbox value as plain data.
pub fn value_of(o: &MontyObject) -> Value {
    to_value(o.as_ref())
}

fn to_value(o: ObjectRef<'_>) -> Value {
    match node(o) {
        MontyNode::None => Value::None,
        MontyNode::Bool(b) => Value::Bool(*b),
        MontyNode::Float(f) => Value::Float(*f),
        MontyNode::String(s) => Value::Str(s.clone()),
        MontyNode::Bytes(b) => Value::Bytes(b.clone()),
        MontyNode::Int(_) | MontyNode::BigInt(_) => o
            .as_int()
            .map_or_else(|| Value::Str(o.py_repr()), Value::Int),
        MontyNode::Dict(_) => Value::Dict(
            o.pairs()
                .unwrap_or_default()
                .into_iter()
                .map(|(k, v)| {
                    (
                        k.as_str().map_or_else(|| k.py_repr(), str::to_string),
                        to_value(v),
                    )
                })
                .collect(),
        ),
        _ => match o.items() {
            Some(items) => Value::List(items.into_iter().map(to_value).collect()),
            None => Value::Str(o.py_repr()),
        },
    }
}

pub fn to_monty(v: &Value) -> MontyObject {
    match v {
        Value::None => MontyObject::none(),
        Value::Bool(b) => MontyObject::bool(*b),
        Value::Int(i) => MontyObject::int(*i),
        Value::Float(f) => MontyObject::float(*f),
        Value::Str(s) => MontyObject::string(s.as_str()),
        Value::Bytes(b) => MontyObject::bytes(b.clone()),
        Value::List(l) => MontyObject::list(l.iter().map(to_monty)),
        Value::Dict(d) => MontyObject::dict(
            d.iter()
                .map(|(k, v)| (MontyObject::string(k.as_str()), to_monty(v))),
        ),
    }
}

fn kwargs(args: &[(&str, Value)]) -> MontyObject {
    MontyObject::dict(
        args.iter()
            .map(|(k, v)| (MontyObject::string(*k), to_monty(v))),
    )
}

