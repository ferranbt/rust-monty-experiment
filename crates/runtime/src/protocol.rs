//! What crosses the sandbox boundary, independent of where the sandbox runs.
//!
//! Shared by the in-process [`MontyRunner`](crate::MontyRunner) and by sandboxes in
//! worker processes (`dut-pool`): the embedded SDK and the `_host` module that
//! imports resolve to, how the host drives the SDK (`engine.py`), how a host-function
//! call from the sandbox is decoded, and how values convert.

use std::collections::BTreeMap;
use std::fmt;

use monty_types::unstable::{MontyNode, node};
use monty_types::{
    CallArgs, ExcType, ImportArgs, ModuleFile, MontyException, MontyObject, MontyUuid, ObjectRef,
};

use crate::helpers;
use crate::host::{Event, EventKind, Framing, HostError, Seconds, SignalKind, TimerSpec, Value};

// `SDK_MODULE` (sandbox import name) and `SDK_FILES` (every `sdk/<SDK_MODULE>/*.py`), generated by build.rs.
include!(concat!(env!("OUT_DIR"), "/sdk.rs"));

pub const SUPPORTED_SDK_VERSIONS: &[&str] = &["0.1"];

/// The embedded SDK package: `(file name, source)` for every `sdk/<SDK_MODULE>/*.py`.
pub fn sdk_files() -> &'static [(&'static str, &'static str)] {
    SDK_FILES
}

/// Script name used in tracebacks.
pub const SCRIPT_NAME: &str = "device.py";
/// Sandbox working directory: top-level imports search here, so `import dut` finds the SDK.
pub const SDK_DIR: &str = "/sdk";
/// Global name the host uses for the SDK's entry points (`engine.py`).
const ENGINE: &str = "_sdk_engine";
const HOST_MODULE: &str = "_host";
const HOST_MODULE_ID: MontyUuid = MontyUuid::from_random_bytes(*b"sandbox-host-mod");
const HOST_FUNCTIONS: &[&str] = &[
    "write",
    "next_event",
    "now",
    "emit",
    "pack",
    "unpack",
    "crc",
    "cobs_encode",
    "cobs_decode",
    "slip_encode",
    "slip_decode",
    "bytes_from_list",
];

