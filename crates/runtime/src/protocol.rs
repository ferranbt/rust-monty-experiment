/// An exception raised by sandbox code, or a syntax error in the script.
#[derive(Debug, Clone, PartialEq)]
pub struct ScriptError {
    /// Python exception type, e.g. `"TimeoutError"`.
    pub exc_type: String,
    pub message: String,
    /// Full traceback as Python would print it.
    pub traceback: String,
}

impl fmt::Display for ScriptError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}: {}", self.exc_type, self.message)
    }
}

impl std::error::Error for ScriptError {}

impl ScriptError {
    pub fn from_monty(e: &MontyException) -> Self {
        Self {
            exc_type: format!("{:?}", e.exc_type()),
            message: e.message().unwrap_or_default().to_string(),
            traceback: e.to_string(),
        }
    }

    /// A failure on the host side of the boundary, reported like a script error.
    pub fn host(message: impl Into<String>) -> Self {
        Self {
            exc_type: "HostError".into(),
            message: message.into(),
            traceback: String::new(),
        }
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct VerbInfo {
    /// Effect the engine confirms by measurement, e.g. `"rf_power"` (silent devices).
    pub confirm: Option<String>,
    /// One of the standard verbs (`status`, `tx_on`, ...) vs a `@dev.verb("name")` extension.
    pub standard: bool,
}

/// What the script declared, read back as plain data after loading.
#[derive(Debug, Clone, PartialEq)]
pub struct Registry {
    pub name: String,
    /// SDK version embedded in this binary.
    pub sdk: String,
    /// SDK version the script declares with `Device(..., sdk="...")`.
    pub sdk_declared: Option<String>,
    pub framing: Framing,
    pub heartbeat_within: Option<Seconds>,
    pub channels: Value,
    pub verbs: BTreeMap<String, VerbInfo>,
    pub hooks: Vec<String>,
    pub handlers: usize,
    pub timers: Vec<TimerSpec>,
    pub readers: Vec<String>,
    /// The `Counter`s and `Gauge`s the script declared, by name.
    pub metrics: BTreeMap<String, MetricInfo>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MetricKind {
    /// Samples are increments; the host keeps the total.
    Counter,
    /// Samples are the current value.
    Gauge,
}

/// A declared metric.
#[derive(Debug, Clone, PartialEq)]
pub struct MetricInfo {
    pub kind: MetricKind,
    pub description: String,
    pub unit: Option<String>,
    /// Label names every sample carries.
    pub labels: Vec<String>,
}

// ---------------------------------------------------------------------------
// Driving the SDK: code the host feeds
// ---------------------------------------------------------------------------

/// A snippet to feed the sandbox plus the inputs it reads.
pub struct Snippet {
    pub code: String,
    pub inputs: Vec<(String, MontyObject)>,
}

impl Snippet {
    fn engine(func: &str, args: Vec<(&str, MontyObject)>) -> Self {
        let params: Vec<_> = args.iter().map(|(k, _)| *k).collect();
        Self {
            code: format!("{ENGINE}.{func}({})", params.join(", ")),
            inputs: args.into_iter().map(|(k, v)| (k.to_string(), v)).collect(),
        }
    }

    /// Imports the SDK and its host entry points. Feed first, then the script source.
    pub fn import_sdk() -> Self {
        Self {
            code: format!("import {SDK_MODULE}.engine as {ENGINE}"),
            inputs: vec![],
        }
    }

    /// Arbitrary code (the script source, or tests).
    pub fn code(code: &str, inputs: &[(&str, Value)]) -> Self {
        Self {
            code: code.to_string(),
            inputs: inputs
                .iter()
                .map(|(k, v)| ((*k).to_string(), to_monty(v)))
                .collect(),
        }
    }

    /// Returns the registry as data; parse it with [`parse_registry`].
    pub fn registry() -> Self {
        Self::engine("registry", vec![])
    }

    pub fn call_verb(name: &str, args: &[(&str, Value)]) -> Self {
        Self::engine(
            "call_verb",
            vec![("name", MontyObject::string(name)), ("args", kwargs(args))],
        )
    }

    pub fn call_hook(name: &str, args: &[(&str, Value)]) -> Self {
        Self::engine(
            "call_hook",
            vec![("name", MontyObject::string(name)), ("args", kwargs(args))],
        )
    }

    pub fn read(name: &str) -> Self {
        Self::engine("read", vec![("name", MontyObject::string(name))])
    }

    pub fn pump(seconds: Seconds) -> Self {
        Self::engine("pump", vec![("seconds", MontyObject::float(seconds))])
    }
}

