// Registry parsing
// ---------------------------------------------------------------------------

fn field<'a>(v: &'a Value, key: &str) -> Result<&'a Value, String> {
    v.get(key)
        .ok_or_else(|| format!("registry: missing {key:?}"))
}

fn usize_field(v: &Value, key: &str) -> Result<usize, String> {
    field(v, key)?
        .as_int()
        .and_then(|i| usize::try_from(i).ok())
        .ok_or_else(|| format!("framing: {key} must be a non-negative int"))
}

fn bytes_field(v: &Value, key: &str) -> Result<Vec<u8>, String> {
    field(v, key)?
        .as_bytes()
        .map(<[u8]>::to_vec)
        .ok_or_else(|| format!("framing: {key} must be bytes"))
}

pub fn parse_framing(v: &Value) -> Result<Framing, String> {
    let mode = field(v, "mode")?
        .as_str()
        .ok_or("framing: mode must be a str")?;
    Ok(match mode {
        "delimiter" => Framing::Delimiter {
            delimiter: bytes_field(v, "delimiter")?,
            keep_empty: matches!(v.get("keep_empty"), Some(Value::Bool(true))),
            max_len: usize_field(v, "max_len")?,
        },
        "cobs" => Framing::Cobs {
            max_len: usize_field(v, "max_len")?,
        },
        "slip" => Framing::Slip {
            max_len: usize_field(v, "max_len")?,
        },
        "hdlc" => Framing::Hdlc {
            max_len: usize_field(v, "max_len")?,
        },
        "length_prefixed" => Framing::LengthPrefixed {
            header: bytes_field(v, "header")?,
            length_offset: usize_field(v, "length_offset")?,
            length_size: usize_field(v, "length_size")?,
            trailer_len: usize_field(v, "trailer_len")?,
            big_endian: field(v, "endian")?.as_str() == Some("big"),
            max_len: usize_field(v, "max_len")?,
        },
        "fixed" => Framing::Fixed {
            size: usize_field(v, "size")?,
        },
        "raw" => Framing::Raw,
        other => return Err(format!("framing: unknown mode {other:?}")),
    })
}

fn strings(v: &Value) -> Vec<String> {
    v.as_list()
        .unwrap_or_default()
        .iter()
        .filter_map(|s| s.as_str().map(str::to_string))
        .collect()
}

pub fn parse_registry(v: &Value) -> Result<Registry, String> {
    let verbs = match field(v, "verbs")? {
        Value::Dict(d) => d
            .iter()
            .map(|(name, info)| {
                let confirm = info
                    .get("confirm")
                    .and_then(Value::as_str)
                    .map(str::to_string);
                let standard = matches!(info.get("standard"), Some(Value::Bool(true)));
                (name.clone(), VerbInfo { confirm, standard })
            })
            .collect(),
        _ => return Err("registry: verbs must be a dict".into()),
    };
    let timers = field(v, "timers")?
        .as_list()
        .unwrap_or_default()
        .iter()
        .map(|t| {
            let id = t
                .get("id")
                .and_then(Value::as_int)
                .ok_or("registry: timer id")?;
            let seconds = t
                .get("seconds")
                .and_then(Value::as_float)
                .ok_or("registry: timer seconds")?;
            Ok(TimerSpec {
                id: id as u32,
                seconds,
            })
        })
        .collect::<Result<_, String>>()?;
    Ok(Registry {
        name: field(v, "name")?.as_str().unwrap_or_default().to_string(),
        sdk: field(v, "sdk")?.as_str().unwrap_or_default().to_string(),
        sdk_declared: v
            .get("sdk_declared")
            .and_then(Value::as_str)
            .map(str::to_string),
        framing: parse_framing(field(v, "framing")?)?,
        heartbeat_within: v.get("heartbeat_within").and_then(Value::as_float),
        channels: v.get("channels").cloned().unwrap_or(Value::None),
        verbs,
        hooks: strings(field(v, "hooks")?),
        handlers: field(v, "handlers")?.as_int().unwrap_or(0) as usize,
        timers,
        readers: strings(field(v, "readers")?),
        metrics: match v.get("metrics") {
            Some(Value::Dict(d)) => d
                .iter()
                .map(|(name, spec)| (name.clone(), metric_info(spec)))
                .collect(),
            _ => BTreeMap::new(),
        },
    })
}

fn metric_info(spec: &Value) -> MetricInfo {
    MetricInfo {
        kind: match spec.get("type").and_then(Value::as_str) {
            Some("counter") => MetricKind::Counter,
            _ => MetricKind::Gauge,
        },
        description: spec
            .get("description")
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string(),
        unit: spec.get("unit").and_then(Value::as_str).map(str::to_string),
        labels: spec.get("labels").map(strings).unwrap_or_default(),
    }
}
